/* utils/escape-html.js
 * Экранирование пользовательских данных перед вставкой в innerHTML.
 *
 * Приложение официально разрешает импорт произвольного JSON (кнопка
 * "Загрузить JSON") — значит поля вроде номера автобуса, маршрута или
 * названия месяца нельзя считать доверенными: специально сформированный
 * файл мог бы содержать, например, bus = '"><img src=x onerror=alert(1)>'.
 * Без экранирования это раньше выполнилось бы как настоящий HTML/JS
 * при следующей отрисовке календаря, подсказок или печатного табеля —
 * в том числе внутри атрибутов (data-value="...", aria-label="..."),
 * где обычного экранирования "<" и ">" недостаточно, нужно экранировать
 * и кавычки.
 */
function escapeHtml(value){
  if(value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
