/* config/app-version.js
 * Версия приложения. Меняйте её при каждом обновлении файлов на хостинге.
 *
 * Зачем это нужно: браузер (особенно мобильный и установленное на главный
 * экран приложение) кеширует css/js и может сколько угодно долго показывать
 * старую версию. Поэтому та же строка подставляется в адреса стилей и скриптов
 * как ?v=... — стоит поменять версию, и браузер обязан скачать файлы заново.
 *
 * ВАЖНО: значение здесь должно совпадать с ?v=... в index.html (bump-version.ps1 меняет всё сразу).
 */
const APP_VERSION = '4.0.5';

// показываем версию в подвале, чтобы всегда можно было проверить,
// какая версия реально открыта на конкретном устройстве
function renderAppVersionLabel(){
  const el = document.getElementById('appVersionLabel');
  if(el) el.textContent = 'v' + APP_VERSION;
}
// Скрипт подключён в конце body, поэтому нужный элемент уже существует —
// рисуем сразу. Дополнительно подписываемся на DOMContentLoaded на случай,
// если порядок подключения когда-нибудь изменится: полагаться только на
// событие нельзя (оно может быть уже позади и не сработает никогда),
// полагаться только на прямой вызов — тоже.
renderAppVersionLabel();
if(document.readyState === 'loading'){
  document.addEventListener('DOMContentLoaded', renderAppVersionLabel);
}
