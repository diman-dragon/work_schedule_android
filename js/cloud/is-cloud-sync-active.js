/* cloud/is-cloud-sync-active.js
 * Синхронизация считается "настроенной на этом устройстве", если пользователь
 * её включил и пароль шифрования сохранён.
 *
 * Раньше здесь дополнительно требовался живой cloudAccessToken. Это и ломало
 * мобильную версию: токен Google живёт ~час и хранится только в sessionStorage,
 * а приложение на главном экране телефона система regularly выгружает из памяти,
 * поэтому после каждого возврата в приложение токена не было — функция
 * возвращала false, и синхронизация молча не выполнялась вообще, без единого
 * сообщения. Токен теперь не признак "настроенности", а то, что запрашивается
 * при самой синхронизации (по нажатию кнопки, где Google-окно не блокируется).
 */
function isCloudSyncActive(){
  return localStorage.getItem(CLOUD_ENABLED_KEY) === '1' && !!cloudPassword;
}
